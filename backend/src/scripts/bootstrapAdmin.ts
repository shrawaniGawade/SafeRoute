import { connectDB, checkDBHealth, disconnectDB } from '../config/db';
import { User } from '../models/User';
import { logAdminAction } from '../models/AuditLog';
import { passwordComplexityRegex } from '../validators/authValidators';
import crypto from 'crypto';

/**
 * Secure One-Time Administrator Bootstrap Script
 *
 * Usage:
 *   npx tsx src/scripts/bootstrapAdmin.ts
 *
 * Environment variables:
 *   BOOTSTRAP_ADMIN_EMAIL    - Target admin email address (default: admin@saferoute.com)
 *   BOOTSTRAP_ADMIN_NAME     - Target admin name (default: System Administrator)
 *   BOOTSTRAP_ADMIN_PASSWORD - Secure password (must satisfy complexity: 8+ chars, upper, lower, digit, symbol)
 *                              If omitted, a cryptographically secure 24-character one-time secret is generated.
 *
 * Command-line flags:
 *   --force                  - Re-promotes or resets the administrator password if the account already exists.
 */
async function bootstrapAdmin(): Promise<void> {
  console.log('========================================================================');
  console.log('  SafeRoute Secure Administrator Account Bootstrap');
  console.log('========================================================================\n');

  try {
    await connectDB();
    const health = await checkDBHealth();
    console.log(`[Bootstrap] Database status: ${health.databaseName || 'InMemoryStore'} (${health.status})\n`);

    // Extract CLI parameters
    const args = process.argv.slice(2);
    const forceFlag = args.includes('--force') || args.includes('-f');

    const emailArg = args.find((a) => a.startsWith('--email='))?.split('=')[1];
    const passwordArg = args.find((a) => a.startsWith('--password='))?.split('=')[1];
    const nameArg = args.find((a) => a.startsWith('--name='))?.split('=')[1];

    const adminEmail = (emailArg || process.env.BOOTSTRAP_ADMIN_EMAIL || process.env.ADMIN_EMAIL || 'admin@saferoute.com')
      .trim()
      .toLowerCase();

    const adminName = (nameArg || process.env.BOOTSTRAP_ADMIN_NAME || process.env.ADMIN_NAME || 'System Administrator').trim();

    let adminPassword = passwordArg || process.env.BOOTSTRAP_ADMIN_PASSWORD || process.env.ADMIN_PASSWORD;
    let isAutoGenerated = false;

    // If no password provided, securely generate high-entropy token
    if (!adminPassword) {
      isAutoGenerated = true;
      const randomBytes = crypto.randomBytes(12).toString('hex');
      adminPassword = `Adm!n#${randomBytes}9A`;
    }

    // Validate password complexity
    if (!passwordComplexityRegex.test(adminPassword)) {
      console.error('[Error] Administrator password failed complexity policy.');
      console.error('Password must contain at least 8 characters, an uppercase letter, lowercase letter, number, and special symbol.');
      process.exit(1);
    }

    // Check if account already exists
    const existing = await User.findOne({ email: adminEmail });

    if (existing) {
      if (!forceFlag && existing.role === 'admin') {
        console.log(`[Info] An active administrator account for "${adminEmail}" already exists.`);
        console.log('       To update or reset this administrator, re-run with the --force flag.\n');
        return;
      }

      console.log(`[Bootstrap] Updating account for "${adminEmail}" to Administrator role...`);
      existing.name = adminName;
      existing.password = adminPassword; // Triggers bcrypt pre-save hash
      existing.role = 'admin';
      existing.isVerified = true;
      await existing.save();

      console.log(`✔ Administrator privileges successfully configured for: ${adminEmail}`);
    } else {
      console.log(`[Bootstrap] Creating initial Administrator account: ${adminEmail}...`);
      await User.create({
        name: adminName,
        email: adminEmail,
        password: adminPassword,
        role: 'admin',
        isVerified: true,
      });

      console.log(`✔ Administrator account successfully provisioned for: ${adminEmail}`);
    }

    // Immutable audit record (with sanitized metadata, zero secrets leaked)
    await logAdminAction({
      action: 'ADMIN_BOOTSTRAP' as any,
      actor: {
        role: 'BOOTSTRAP_CLI',
        email: adminEmail,
      },
      target: {
        resourceType: 'User',
        resourceName: adminEmail,
      },
      status: 'SUCCESS',
      metadata: {
        timestamp: new Date().toISOString(),
        action: 'Administrator account provisioned via controlled script',
        isAutoGenerated,
      },
    });

    console.log('\n------------------------------------------------------------------------');
    console.log('CREDENTIAL SUMMARY:');
    console.log(`  Email: ${adminEmail}`);
    console.log(`  Role:  admin`);
    if (isAutoGenerated) {
      console.log(`  One-Time Generated Password: ${adminPassword}`);
      console.log('  [IMPORTANT] Store this temporary secret securely; it is never logged or saved in plaintext.');
    } else {
      console.log('  Password: [SUPPLIED VIA SECURE ENVIRONMENT / ARGUMENT]');
    }
    console.log('------------------------------------------------------------------------\n');
  } catch (error) {
    console.error('[Bootstrap Error] Failed to bootstrap administrator:', error);
    process.exit(1);
  } finally {
    await disconnectDB();
  }
}

if (require.main === module || process.argv[1]?.includes('bootstrapAdmin')) {
  bootstrapAdmin();
}

export { bootstrapAdmin };
